    async def save_ride(
        self,
        ride: dict[str, Any],
        *,
        bookmark: bool = False,
        imported: bool = False,
        dont_save: bool = False,
    ) -> dict[str, Any] | None:
        """Save a new ride.

        ride is shaped like the app's RidePostRequest: name, description, type
        ("CUSTOM"), subType ("RECORDED" or "PLANNED"), waypoints, locationHistory,
        rideAvoidances and so on, with dates as "yyyy-mm-ddThh:mm:ss+0000". Returns
        the ride and record summaries.
        """
        data = await self._request(
            "POST",
            "ride",
            params={
                "dontSave": dont_save,
                "imported": imported or None,
                "bookmarkStatus": bookmark,
            },
            # the backend expects the ride as JSON encoded string
            body={"ride": json.dumps(ride)},
        )
        return _dict(data, "data")

