    # Rides

    async def get_rides(
        self,
        latitude: float,
        longitude: float,
        *,
        radius_miles: float | None = None,
        limit: int | None = None,
        sub_types: Iterable[str] = (),
        tags: Iterable[str] = (),
        include_location_history: bool = False,
        include_bookmarked: bool = True,
    ) -> list[dict[str, Any]]:
        """Curated rides around a position.

        sub_types are HD or DEALER. tags are "tag=<name>" strings, the app knows the
        names eaglerider, short-rides, day-rides, overnight-rides, lets-ride,
        sturgis-rides, milwaukee-rides and daytona-rides.
        """
        data = await self._request(
            "GET",
            "rides",
            params={
                "lat": latitude,
                "lon": longitude,
                "radiusInMiles": radius_miles,
                "limit": limit,
                "type": "CURATED",
                "subType": list(sub_types),
                "tag": list(tags),
                "includeLocationHistory": include_location_history,
                "includeBookmarked": include_bookmarked,
            },
        )
        return _list(data, "rides")

